CREATE TABLE IF NOT EXISTS ride_classes (
    id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    source_key VARCHAR(100) NULL UNIQUE,
    class_name VARCHAR(190) NOT NULL,
    class_code VARCHAR(32) NOT NULL UNIQUE,
    class_group VARCHAR(32) NOT NULL,
    distance_km INT UNSIGNED NULL,
    price DECIMAL(10,2) NOT NULL,
    foreign_recognition_price DECIMAL(10,2) NULL,
    is_member_price TINYINT(1) NOT NULL DEFAULT 0,
    is_junior_ride TINYINT(1) NOT NULL DEFAULT 0,
    rider_eligibility VARCHAR(20) NOT NULL DEFAULT 'all',
    sort_order INT UNSIGNED NOT NULL DEFAULT 10,
    is_active TINYINT(1) NOT NULL DEFAULT 1,
    show_on_public TINYINT(1) NOT NULL DEFAULT 1,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS ride_scheme_classes (
    scheme_id INT UNSIGNED NOT NULL,
    class_id INT UNSIGNED NOT NULL,
    sort_order INT UNSIGNED NOT NULL DEFAULT 10,
    PRIMARY KEY(scheme_id,class_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS event_pricing_locks (
    event_id INT UNSIGNED PRIMARY KEY,
    locked_at DATETIME NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS ride_pricing_state (
    migration_key VARCHAR(100) PRIMARY KEY,
    source_sha256 CHAR(64) NOT NULL,
    applied_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
